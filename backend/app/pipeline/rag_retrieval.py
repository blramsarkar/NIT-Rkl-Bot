def search_docs(query: str, source_section: Optional[str] = None, top_k: int = 3) -> List[Dict[str, Any]]:
    """
    Executes semantic vector search against stored document chunks in the database.
    Encodes the incoming query to a 384-dimensional dense vector and computes
    cosine similarity against chunk embeddings stored in PostgreSQL / SQLite.
    """
    if not query or not query.strip():
        return []

    hits = []
    db: Session = SessionLocal()

    try:
        chunks_query = db.query(DocumentChunk)
        if source_section:
            chunks_query = chunks_query.filter(DocumentChunk.category.ilike(f"%{source_section}%"))

        chunks = chunks_query.all()
        if chunks:
            # 1. Compute query vector
            query_vector = encode_text(query)
            query_tokens = set(query.lower().split())

            scored_chunks = []
            for chunk in chunks:
                # Dense vector similarity
                if chunk.embedding and isinstance(chunk.embedding, list) and len(chunk.embedding) > 0:
                    vec_sim = cosine_similarity(query_vector, chunk.embedding)
                else:
                    vec_sim = 0.0

                # Keyword overlap boost (hybrid scoring)
                content_lower = chunk.content.lower()
                token_matches = sum(1 for token in query_tokens if token in content_lower)
                kw_score = min(token_matches / max(len(query_tokens), 1), 1.0)

                # Combined hybrid score (75% vector semantics, 25% keyword match)
                hybrid_score = (0.75 * vec_sim) + (0.25 * kw_score)
                scored_chunks.append((hybrid_score, vec_sim, chunk))

            # Filter out irrelevant chunks below minimum semantic confidence threshold (NFR: Zero Hallucination)
            MIN_RELEVANCE_THRESHOLD = 0.30
            filtered_chunks = [c for c in scored_chunks if c[0] >= MIN_RELEVANCE_THRESHOLD]

            # Rank by hybrid score descending
            filtered_chunks.sort(key=lambda x: x[0], reverse=True)
            top_matches = filtered_chunks[:top_k]

            for hybrid_score, vec_sim, chunk in top_matches:
                meta = chunk.chunk_metadata or {}
                hits.append({
                    "source_url": meta.get("source_url") or page_for_category(chunk.category),
                    "document_name": chunk.document_name,
                    "category": chunk.category,
                    "content": chunk.content,
                    "chunk_metadata": chunk.chunk_metadata or {},
                    "score": round(hybrid_score, 4),
                    "vector_similarity": round(vec_sim, 4)
                })
    except Exception as e:
        logger.warning(f"Vector search in DB encountered an exception: {e}.")
    finally:
        db.close()

    # If database returned evaluated results (or rejected as low relevance), return hits directly
    # Do NOT inject random default snippets for out-of-domain queries
    return hits


# Alias for backwards compatibility
perform_vector_search = search_docs
